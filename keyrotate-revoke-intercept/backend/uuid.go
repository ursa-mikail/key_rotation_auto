package main

import (
	"crypto/rand"
	"fmt"
)

// newUUIDv4 generates a random (version 4, variant 1) UUID string.
// A tiny local helper so the module doesn't need an extra dependency
// just for this.
func newUUIDv4() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	b[6] = (b[6] & 0x0f) | 0x40 // version 4
	b[8] = (b[8] & 0x3f) | 0x80 // variant 10
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16]), nil
}
